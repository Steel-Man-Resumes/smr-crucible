#!/usr/bin/env node
/**
 * THE PACKAGER.
 *
 *   node build.mjs                 build both SCORM 1.2 and 2004 packages
 *   node build.mjs --scorm 1.2     build only 1.2
 *   node build.mjs --scorm 2004    build only 2004
 *
 * Three jobs, in this order, and it stops at the first failure:
 *
 *   1. GENERATE the manifest from the actual file list on disk. The single
 *      most common reason a SCORM package is rejected is a file that exists in
 *      the zip but is missing from the manifest. Hand-maintaining that list
 *      guarantees it happens eventually, so nothing here is hand-maintained.
 *
 *   2. PREFLIGHT every byte that is about to be zipped against the containment
 *      rules in preflight.mjs, and fail the build on any blocking finding. A
 *      package that can reach the network cannot be produced by this script.
 *
 *   3. ZIP with the manifest at the root, written by hand with node:zlib so
 *      the toolchain has no dependencies either. The other common rejection is
 *      zipping the containing folder instead of its contents. That is not
 *      possible here: entries are named from the file list, not from a path.
 *
 * The report written alongside the zip is a deliverable, not a build log. It
 * is the thing that goes to CypherWorx and to ViaPath with the package.
 */

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { join, relative, dirname, extname } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateRawSync } from "node:zlib";
import { preflight, renderReport } from "./preflight.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "src");
const DIST = join(HERE, "dist");

/* ------------------------------------------------------------- identity */

/**
 * FORGE TABLET. Named by Troy 2026-09-11.
 *
 * The naming convention across the family is literal and descriptive: The
 * Forge and The Refinery on the web, Forge Tablet in a facility, and Refinery
 * Tablet if and when that one is built. A person in a facility and a vetting
 * reviewer reading a catalog listing should both be able to tell what it is
 * without being told.
 *
 * Everything a human sees is in this one object, so a rename is a one-line
 * change and a rebuild. PACKAGE_ID is the exception: it is what the LMS
 * stores, so once a package has been submitted for vetting it must not change.
 * A new identifier reads to an LMS as an unrelated course and disconnects
 * every learner record already attached to the old one.
 */
const BRAND = {
  PACKAGE_ID: "SMR_FORGE_TABLET",
  COURSE_TITLE: "Forge Tablet",
  ITEM_TITLE: "Forge Tablet",
  ORGANIZATION: "Steel Man Resumes",
  DESCRIPTION:
    "A short, offline career intake. Seven questions about what you are good at " +
    "and what you want next. Produces a code the learner carries out with them.",
  VERSION: "1.1",
  // Typical duration, ISO 8601. Used by some LMS catalogs for the course card.
  TYPICAL_DURATION: "PT10M"
};

/* ------------------------------------------------------------ file list */

/** Every file under src/, sorted, with forward-slash names for the zip. */
function collectFiles(dir, base = dir) {
  const out = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...collectFiles(full, base));
    else out.push({ path: full, name: relative(base, full).split("\\").join("/") });
  }
  return out;
}

/* -------------------------------------------------------------- manifest */

function xmlEscape(s) {
  return String(s)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}

function manifest12(files) {
  const fileLines = files.map((f) => `      <file href="${xmlEscape(f.name)}"/>`).join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  SCORM 1.2 content package manifest.
  GENERATED by build.mjs from the contents of src/. Do not hand edit: the next
  build overwrites it, and a hand edit is how a file goes undeclared.
-->
<manifest identifier="${xmlEscape(BRAND.PACKAGE_ID)}_12" version="${xmlEscape(BRAND.VERSION)}"
  xmlns="http://www.imsproject.org/xsd/imscp_rootv1p1p2"
  xmlns:adlcp="http://www.adlnet.org/xsd/adlcp_rootv1p2"
  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
  xsi:schemaLocation="http://www.imsproject.org/xsd/imscp_rootv1p1p2 imscp_rootv1p1p2.xsd
                      http://www.adlnet.org/xsd/adlcp_rootv1p2 adlcp_rootv1p2.xsd
                      http://www.imsglobal.org/xsd/imsmd_rootv1p2p1 imsmd_rootv1p2p1.xsd">

  <metadata>
    <schema>ADL SCORM</schema>
    <schemaversion>1.2</schemaversion>
  </metadata>

  <organizations default="ORG">
    <organization identifier="ORG">
      <title>${xmlEscape(BRAND.COURSE_TITLE)}</title>
      <item identifier="ITEM" identifierref="RES" isvisible="true">
        <title>${xmlEscape(BRAND.ITEM_TITLE)}</title>
        <!--
          masteryscore 0: this is an intake, not an assessment. There is no
          score, nothing is graded, and no answer is wrong. Completion is the
          only outcome reported.
        -->
        <adlcp:masteryscore>0</adlcp:masteryscore>
        <adlcp:maxtimeallowed>04:00:00.00</adlcp:maxtimeallowed>
        <adlcp:datafromlms></adlcp:datafromlms>
      </item>
    </organization>
  </organizations>

  <resources>
    <resource identifier="RES" type="webcontent" adlcp:scormtype="sco" href="index.html">
${fileLines}
    </resource>
  </resources>
</manifest>
`;
}

